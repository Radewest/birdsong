"""Generate Atlas.lua: every Classic bird creature with level, zones and display (model) ID.
Sources (parsed as text, never executed):
  - cmangos classic-db (creature_template: name, levels, family, type, model IDs)  github.com/cmangos/classic-db
  - pfQuest database (spawn zones)                                                github.com/shagu/pfQuest
"""
import json
birds=json.load(open('birds.json'))
SKIP={9526,9527}  # Enraged Gryphon/Hippogryph: flight-path event spawns, not wild birds
def q(s): return '"'+s.replace('\\\'',"'").replace('\\','\\\\').replace('"','\\"')+'"'
lines=['-- Birdsong: the Atlas. Every bird creature in the classic world. GENERATED by tools/gen_atlas.py, do not hand-edit.',
'-- Sources: cmangos classic-db (names, levels, families, models) and pfQuest (spawn zones).',
'-- n = name, s = species key, l1/l2 = levels, d = display (model) ID, rare = rare spawn, z = zones (most spawns first)',
'local _, ns = ...','ns.KINDS = {']
for b in birds:
    if b['id'] in SKIP: continue
    zs=[z.replace("\\'","'") for z,_ in sorted(b['zones'].items(),key=lambda x:-x[1])]
    lines.append(f'  [{b["id"]}] = {{ n = {q(b["name"])}, s = "{b["sp"]}", l1 = {b["minl"]}, l2 = {b["maxl"]}, d = {b["display"]},{" rare = true," if b.get("rank") in (2,4) else ""} z = {{ {", ".join(q(z) for z in zs)} }} }},')
lines.append('}')
print('\n'.join(lines))
