"""Generate Spawns.lua (map pins) from pfQuest's db/units.lua + db/enUS/zones.lua (parsed as text, never run).
Run in the scratch folder that holds pfq/ (pfQuest clone) and birds.json (from birds_db.py)."""
import json, re
units = {}; cur = None
for line in open('pfq/db/units.lua', encoding='utf-8'):
    m = re.match(r'^  \[(\d+)\] = \{', line)
    if m: cur = int(m.group(1)); units[cur] = []; continue
    m = re.match(r'^\s+\[\d+\] = \{ ([\d.]+), ([\d.]+), (\d+), (\d+) \},', line)
    if m and cur is not None: units[cur].append((float(m.group(1)), float(m.group(2)), int(m.group(3))))
zn = {}
for line in open('pfq/db/enUS/zones.lua', encoding='utf-8'):
    m = re.match(r'^\s+\[(\d+)\] = "(.*)",\s*$', line)
    if m: zn[int(m.group(1))] = m.group(2).replace("\\'", "'")
birds = json.load(open('birds.json'))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
L = ['-- Birdsong: spawn points for map pins. GENERATED by tools/gen_spawns.py from pfQuest (github.com/shagu/pfQuest).',
     '-- ns.SPAWNS[npcID][zoneName] = { x1, y1, x2, y2, ... } in zone map percent (0-100)', 'local _, ns = ...', 'ns.SPAWNS = {']
for b in birds:
    if b['id'] in (9526, 9527): continue
    byz = {}
    for x, y, z in units.get(b['id'], []):
        byz.setdefault(zn.get(z, str(z)), []).append((x, y))
    parts = []
    for z, pts in byz.items():
        kept = []  # thin dense clusters: drop points within 1.5% of one already kept
        for p in pts:
            if all(abs(p[0] - k[0]) > 1.5 or abs(p[1] - k[1]) > 1.5 for k in kept): kept.append(p)
        parts.append(f'[{q(z)}] = {{ {", ".join(f"{x:g}, {y:g}" for x, y in kept)} }}')
    L.append(f'  [{b["id"]}] = {{ {", ".join(parts)} }},')
L.append('}')
print('\n'.join(L))
